// Command import-native verifies the bundled assets offline, or reimports the
// exact pinned bytes with -fetch. Run from the repository root.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"time"
)

const directory = "internal/phy/native"

type asset struct {
	Name   string `json:"name"`
	URL    string `json:"url"`
	SHA256 string `json:"sha256"`
}

func main() {
	fetch := flag.Bool("fetch", false, "download and verify the pinned upstream assets")
	flag.Parse()
	if err := run(*fetch); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(fetch bool) error {
	data, err := os.ReadFile(filepath.Join(directory, "manifest.json"))
	if err != nil {
		return err
	}
	var manifest struct {
		Files []asset `json:"files"`
	}
	if err := json.Unmarshal(data, &manifest); err != nil {
		return err
	}
	if len(manifest.Files) == 0 {
		return fmt.Errorf("empty native asset manifest")
	}
	client := &http.Client{Timeout: time.Minute}
	for _, file := range manifest.Files {
		if filepath.Base(file.Name) != file.Name {
			return fmt.Errorf("invalid asset path %q", file.Name)
		}
		path := filepath.Join(directory, file.Name)
		var contents []byte
		if fetch {
			contents, err = download(client, file.URL)
		} else {
			contents, err = os.ReadFile(path)
		}
		if err != nil {
			return fmt.Errorf("%s: %w", file.Name, err)
		}
		if hash := fmt.Sprintf("%x", sha256.Sum256(contents)); hash != file.SHA256 {
			return fmt.Errorf("%s: checksum %s, expected %s", file.Name, hash, file.SHA256)
		}
		if filepath.Ext(path) == ".a" && !bytes.HasPrefix(contents, []byte("!<arch>\n")) {
			return fmt.Errorf("%s: not a real archive", file.Name)
		}
		if fetch {
			if err := os.WriteFile(path, contents, 0o644); err != nil {
				return err
			}
		}
		fmt.Println("verified", file.Name)
	}
	rom, err := os.ReadFile(filepath.Join(directory, "esp32c6.rom.phy.ld"))
	if err != nil {
		return err
	}
	assembly, err := romAssembly(rom)
	if err != nil {
		return err
	}
	path := "internal/phy/rom_esp32c6.c"
	if fetch {
		return os.WriteFile(path, assembly, 0o644)
	}
	existing, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !bytes.Equal(existing, assembly) {
		return fmt.Errorf("%s: generated ROM bindings differ; reimport with -fetch", path)
	}
	fmt.Println("verified generated ROM bindings")
	return nil
}

func download(client *http.Client, url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: HTTP %s", url, resp.Status)
	}
	const limit = 2 << 20
	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		return nil, err
	}
	if len(data) > limit {
		return nil, fmt.Errorf("%s: asset exceeds %d bytes", url, limit)
	}
	return data, nil
}

func romAssembly(script []byte) ([]byte, error) {
	matches := regexp.MustCompile(`(?m)^([a-zA-Z_][a-zA-Z_0-9]*) = (0x[0-9a-fA-F]+);$`).FindAllSubmatch(script, -1)
	if len(matches) == 0 {
		return nil, fmt.Errorf("no ROM symbols in pinned linker script")
	}
	var out bytes.Buffer
	out.WriteString("//go:build tinygo && esp32c6\n\n")
	out.WriteString("// Code generated by tools/import-native; DO NOT EDIT.\n")
	out.WriteString("// SPDX-FileCopyrightText: 2022 Espressif Systems (Shanghai) CO LTD\n")
	out.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	for _, m := range matches {
		fmt.Fprintf(&out, "__asm__(\".weak %s\\n.set %s, %s\\n\");\n", m[1], m[1], m[2])
	}
	return out.Bytes(), nil
}
