// Command lab prepares firmware/evidence and evaluates explicit captured files.
// It NEVER enumerates, opens, resets, flashes or controls attached devices.
package main

import (
	"bufio"
	"crypto/rand"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/hilli/esp32c6-radio/internal/image"
	"github.com/hilli/esp32c6-radio/lab"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run(args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: lab build|collect|commands (no attached-device operations)")
	}
	switch args[0] {
	case "build":
		return build(args[1:])
	case "collect":
		return collect(args[1:])
	case "commands":
		return commands(args[1:])
	default:
		return fmt.Errorf("unknown lab operation")
	}
}
func command(args ...string) (string, error) {
	c := exec.Command(args[0], args[1:]...)
	p, err := c.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("%s: %w\n%s", strings.Join(args, " "), err, p)
	}
	return strings.TrimSpace(string(p)), nil
}
func hashFile(path string) (string, error) {
	info, err := os.Stat(path)
	if err != nil {
		return "", err
	}
	if !info.Mode().IsRegular() || info.Size() > 64<<20 {
		return "", fmt.Errorf("artifact must be a bounded regular file")
	}
	p, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	h := sha256.Sum256(p)
	return hex.EncodeToString(h[:]), nil
}
func save(path string, v any) error {
	p, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return err
	}
	if err := file.Chmod(0o600); err != nil {
		file.Close()
		return err
	}
	_, writeErr := file.Write(append(p, '\n'))
	closeErr := file.Close()
	if writeErr != nil {
		return writeErr
	}
	return closeErr
}
func readManifest(path string) (lab.Manifest, error) {
	var m lab.Manifest
	p, err := os.ReadFile(path)
	if err != nil {
		return m, err
	}
	err = json.Unmarshal(p, &m)
	return m, err
}
func sourceFingerprint() (string, error) {
	files, err := command("git", "ls-files", "--cached", "--others", "--exclude-standard", "-z")
	if err != nil {
		return "", err
	}
	h := sha256.New()
	for _, name := range strings.Split(files, "\x00") {
		if name == "" || strings.HasSuffix(name, ".md") {
			continue
		}
		p, err := os.ReadFile(name)
		if err != nil {
			return "", err
		}
		h.Write([]byte(name))
		sum := sha256.Sum256(p)
		h.Write(sum[:])
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}
func build(args []string) error {
	f := flag.NewFlagSet("build", flag.ContinueOnError)
	probe := f.String("probe", "storage", "storage, entropy, rf-validation or thread-validation")
	out := f.String("out", "build/lab", "output directory")
	board := f.String("board", "", "expected board model; blank leaves physical identity NOT_RUN")
	eui := f.String("expected-eui", "", "expected canonical EUI64 from independently approved device identification")
	runID := f.String("run-id", "", "existing paired-board campaign ID; default generates a new host CSPRNG ID")
	if err := f.Parse(args); err != nil {
		return err
	}
	if *probe != "storage" && *probe != "entropy" && *probe != "rf-validation" && *probe != "thread-validation" {
		return fmt.Errorf("unsupported probe")
	}
	commit, err := command("git", "rev-parse", "HEAD")
	if err != nil {
		return err
	}
	fingerprint, err := sourceFingerprint()
	if err != nil {
		return err
	}
	version, err := command("tinygo", "version")
	if err != nil {
		return err
	}
	firmware := sha256.Sum256([]byte(fingerprint + "\n" + version + "\n" + *probe))
	id := hex.EncodeToString(firmware[:])
	var nonce [16]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		return err
	}
	m := lab.Manifest{Version: 1, RunID: hex.EncodeToString(nonce[:]), FirmwareID: id, Commit: commit, Board: *board, ExpectedEUI: strings.ToLower(*eui),
		GoVersion: runtime.Version(), TinyGoVersion: version, NativeRevision: "IDF-8c750b088c7cd857d079c0eeb495da199b359461/PHY-f6746ceea821b3800e8700d7e535f5df7304b8e5"}
	m.Probe = *probe
	m.SourceFingerprint = fingerprint
	if *runID != "" {
		p, err := hex.DecodeString(*runID)
		if err != nil || len(p) != 16 {
			return fmt.Errorf("run-id must be 16 host-generated bytes in hex")
		}
		m.RunID = *runID
	}
	if err := os.MkdirAll(*out, 0o700); err != nil {
		return err
	}
	for _, ext := range []string{"elf", "bin"} {
		path := filepath.Join(*out, "firmware."+ext)
		if _, err := command("tinygo", "build", "-target", "./targets/esp32c6-radio.json", "-ldflags", "-X main.firmwareID="+id, "-o", path, "./examples/"+*probe); err != nil {
			return err
		}
	}
	if _, err := image.Check(filepath.Join(*out, "firmware.elf"), filepath.Join(*out, "firmware.bin")); err != nil {
		return err
	}
	m.ELFSHA256, err = hashFile(filepath.Join(*out, "firmware.elf"))
	if err != nil {
		return err
	}
	m.BinSHA256, err = hashFile(filepath.Join(*out, "firmware.bin"))
	if err != nil {
		return err
	}
	if err := save(filepath.Join(*out, "manifest.json"), m); err != nil {
		return err
	}
	if err := save(filepath.Join(*out, "evidence.json"), lab.Evaluate(m, nil)); err != nil {
		return err
	}
	fmt.Println("Firmware built; all physical gates NOT_RUN. No attached device was accessed.")
	fmt.Println("firmware_id:", id)
	return nil
}
func collect(args []string) error {
	f := flag.NewFlagSet("collect", flag.ContinueOnError)
	manifest := f.String("manifest", "", "exact build manifest")
	input := f.String("input", "", "captured regular-file serial log (not a device)")
	output := f.String("out", "evidence.json", "0600 evidence report")
	witnessPath := f.String("witness", "", "independent sniffer/reference-peer witness JSON")
	artifactPath := f.String("artifact", "", "actual regular-file peer/sniffer capture hashed by this host")
	if err := f.Parse(args); err != nil {
		return err
	}
	m, err := readManifest(*manifest)
	if err != nil {
		return err
	}
	info, err := os.Stat(*input)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Size() > 128<<20 {
		return fmt.Errorf("input must be a captured regular file; device access is forbidden")
	}
	file, err := os.Open(*input)
	if err != nil {
		return err
	}
	defer file.Close()
	s := bufio.NewScanner(file)
	s.Buffer(make([]byte, 8192), 8192)
	var events []lab.Event
	for s.Scan() {
		if !strings.HasPrefix(s.Text(), lab.Prefix) {
			continue
		}
		e, err := lab.Parse(s.Bytes())
		if err != nil {
			return err
		}
		if len(events) >= 100000 {
			return fmt.Errorf("evidence event limit")
		}
		events = append(events, e)
	}
	if err := s.Err(); err != nil {
		return err
	}
	report := lab.Evaluate(m, events)
	if *witnessPath != "" {
		p, err := os.ReadFile(*witnessPath)
		if err != nil {
			return err
		}
		var w lab.Witness
		if err := json.Unmarshal(p, &w); err != nil {
			return err
		}
		hash, err := hashFile(*artifactPath)
		if err != nil {
			return err
		}
		if err := lab.ApplyWitness(m, &report, w, hash); err != nil {
			if saveErr := save(*output, report); saveErr != nil {
				return fmt.Errorf("%w; evidence persistence failed: %v", err, saveErr)
			}
			return err
		}
	}
	if err := save(*output, report); err != nil {
		return err
	}
	if len(events) == 0 {
		return fmt.Errorf("no device evidence; report preserved as NOT_RUN")
	}
	for _, status := range report.Checks {
		if status == lab.Fail {
			return fmt.Errorf("physical evidence contains FAIL; report preserved")
		}
		required := []string{"identity"}
		switch m.Probe {
		case "storage":
			required = append(required, "storage_safety", "storage_recovery")
		case "entropy":
			required = append(required, "entropy_health")
		case "rf-validation":
			required = append(required, "rf")
		case "thread-validation":
			required = append(required, "thread")
		}
		for _, name := range required {
			if report.Checks[name] != lab.Pass {
				return fmt.Errorf("%s is %s; evidence retained but campaign is not complete", name, report.Checks[name])
			}
		}
	}
	fmt.Println("Evidence preserved; NOT_RUN gates remain NOT_RUN. Statistical smoke is not entropy qualification.")
	return nil
}
func commands(args []string) error {
	f := flag.NewFlagSet("commands", flag.ContinueOnError)
	path := f.String("manifest", "", "build manifest")
	operation := f.String("operation", "hello", "hello, observe, format, write, run")
	boot := f.String("boot", "", "independent host boot/cut identifier")
	counter := f.Uint64("counter", 0, "disposable storage test counter, never a secret")
	scope := f.String("approve-scope", "", "explicit EUI64:action:run_id acknowledgement; prints commands only")
	probe := f.String("probe", "storage", "storage, entropy, rf or thread")
	channel := f.Uint("channel", 0, "explicit lab channel 11-26")
	pan := f.Uint("pan", 0, "explicit disposable lab PAN ID 1..65534; no default")
	local := f.Uint("local", 0xffff, "explicit local short address")
	peer := f.Uint("peer", 0xffff, "explicit peer short address")
	count := f.Uint("count", 1000, "directed packet count")
	duration := f.Uint("duration", 1800, "attached Thread campaign duration seconds")
	peerIP := f.String("peer-ipv6", "", "explicit isolated reference-peer IPv6 address")
	delay := f.Uint("delay-ms", 0, "controlled storage checkpoint delay, maximum 2000")
	dataset := f.String("dataset-file", "", "private lab dataset hex; output then requires -out-command")
	privateOut := f.String("out-command", "", "0600 private command file; never echoed when dataset is supplied")
	storageEvidence := f.String("storage-evidence", "", "physical storage campaign evidence required for Thread")
	entropyEvidence := f.String("entropy-evidence", "", "physical entropy health evidence required for Thread; not source qualification")
	sourceReview := f.String("source-review", "", "operator source/board review document; not a statistical certification")
	if err := f.Parse(args); err != nil {
		return err
	}
	m, err := readManifest(*path)
	if err != nil {
		return err
	}
	if len(m.ExpectedEUI) != 16 || m.Board == "" || *boot == "" {
		return fmt.Errorf("explicit board/EUI/boot identity required")
	}
	action := "0x3f8000"
	if *probe == "entropy" {
		action = "phy-entropy"
	} else if *probe == "rf" {
		action = "rf"
	} else if *probe == "thread" {
		action = "thread-lab"
	} else if *probe != "storage" {
		return fmt.Errorf("unknown probe")
	}
	if *operation != "hello" && *operation != "observe" && *scope != m.ExpectedEUI+":"+action+":"+m.RunID {
		return fmt.Errorf("destructive/RF scope not approved")
	}
	if *operation != "hello" && *operation != "observe" && *operation != "format" && *operation != "write" && *operation != "run" && *operation != "start" {
		return fmt.Errorf("unknown operation")
	}
	if *channel > 26 || *pan > 65535 || *local > 65535 || *peer > 65535 || *count > 10000 || *duration > 3600 || *delay > 2000 {
		return fmt.Errorf("campaign bound exceeded")
	}
	c := lab.Command{Operation: *operation, RunID: m.RunID, BootID: *boot, ExpectedEUI: m.ExpectedEUI, Confirmation: *scope,
		Counter: *counter, DelayMillis: uint32(*delay), Channel: uint8(*channel), PanID: uint16(*pan), LocalAddress: uint16(*local), PeerAddress: uint16(*peer),
		Count: uint32(*count), DurationSeconds: uint32(*duration), PeerIPv6: *peerIP}
	if *probe == "rf" && *operation == "run" && (*channel < 11 || *pan == 0 || *pan == 65535 || *local == *peer || *local == 65535 || *peer == 65535 || *count < 1000) {
		return fmt.Errorf("explicit isolated RF channel, nonzero non-broadcast lab PAN and unicast addresses required")
	}
	if *probe == "thread" && *operation == "start" {
		c.StorageReviewArtifact, err = requirePhysicalReport(*storageEvidence, m.ExpectedEUI, "storage_safety", "storage_recovery")
		if err != nil {
			return err
		}
		c.EntropyReviewArtifact, err = requirePhysicalReport(*entropyEvidence, m.ExpectedEUI, "entropy_health")
		if err != nil {
			return err
		}
		review, err := os.ReadFile(*sourceReview)
		if err != nil {
			return err
		}
		var qualification struct {
			DeviceEUI       string   `json:"device_eui64"`
			NativeRevision  string   `json:"native_revision"`
			SourceArtifacts []string `json:"source_artifacts"`
			Review          string   `json:"review"`
		}
		if err := json.Unmarshal(review, &qualification); err != nil {
			return err
		}
		if qualification.DeviceEUI != m.ExpectedEUI || qualification.NativeRevision != m.NativeRevision || len(qualification.SourceArtifacts) < 2 || len(qualification.Review) < 128 {
			return fmt.Errorf("source/board review with actual PHY/clock/analogue evidence references is required; smoke tests do not qualify entropy")
		}
		c.SourceReviewArtifact, err = hashFile(*sourceReview)
		if err != nil {
			return err
		}
		if *dataset != "" {
			if *privateOut == "" {
				return fmt.Errorf("private dataset commands must be written to -out-command, never stdout")
			}
			p, err := os.ReadFile(*dataset)
			if err != nil {
				return err
			}
			if len(p) > 1024 {
				return fmt.Errorf("dataset input too large")
			}
			c.DatasetHex = strings.TrimSpace(string(p))
		}
	}
	if *privateOut != "" {
		return save(*privateOut, c)
	}
	return json.NewEncoder(os.Stdout).Encode(c)
}

func requirePhysicalReport(path, eui string, checks ...string) (string, error) {
	p, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var r lab.Report
	if err := json.Unmarshal(p, &r); err != nil {
		return "", err
	}
	if r.Version != lab.Version || r.Origin != "physical" || r.DeviceEUI != eui || r.FirmwareID == "" || r.Checks["identity"] != lab.Pass {
		return "", fmt.Errorf("real identified physical evidence required")
	}
	for _, name := range checks {
		if r.Checks[name] != lab.Pass {
			return "", fmt.Errorf("physical %s has not passed", name)
		}
	}
	return hashFile(path)
}
